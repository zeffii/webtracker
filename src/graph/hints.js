for (let k = 1; k <= 4; k++) {
  Object.assign(HINTS.fmsynth, {
    [`atk${k}`]: `Operator ${k} attack in ms. For a modulator, a slow attack brings the brightness in gradually.`,
    [`dec${k}`]: `Operator ${k} decay in ms, down to its sustain level.`,
    [`sus${k}`]: `Operator ${k} sustain level while the note is held, 0 to 1. For a modulator it is how bright the held note stays.`,
    [`rel${k}`]: `Operator ${k} release in ms.`,
  });
}

export const hintFor = (type, spec) => HINTS[type]?.[spec.name] ?? COMMON[spec.name] ?? '';

// A line of facts about the parameter's range, from its definition.
export const factsFor = spec => {
  const f = n => (Number.isInteger(n) ? String(n) : String(Math.round(n * 1000) / 1000));
  const bits = [`range ${f(spec.min)} to ${f(spec.max)}`, `default ${f(spec.def)}`];
  if (spec.scale === 'log') bits.push('logarithmic slider');
  if (spec.int) bits.push('whole numbers');
  return bits.join(' · ');
};
