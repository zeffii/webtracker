// Dev-only: compiles assembly/dsp.ts and embeds the result as base64 in
// src/audio/wasm/dsp.wasm.js, which is committed so the app needs no build step.
import asc from 'assemblyscript/asc';
import { writeFileSync, mkdirSync } from 'node:fs';

mkdirSync('build', { recursive: true });
const { error, stderr } = await asc.main([
  'assembly/dsp.ts', '--outFile', 'build/dsp.wasm',
  '--importMemory', '--runtime', 'stub', '--noAssert',
  '--optimizeLevel', '3', '--shrinkLevel', '1', '--disable', 'bulk-memory',
]);
if (error) { console.error(stderr.toString()); process.exit(1); }
const { readFileSync } = await import('node:fs');
const bytes = readFileSync('build/dsp.wasm');
writeFileSync('src/audio/wasm/dsp.wasm.js',
  `// Generated by scripts/build-wasm.mjs from assembly/dsp.ts. Do not edit.\nexport const DSP_WASM_BASE64 = '${bytes.toString('base64')}';\n`);
console.log(`dsp.wasm: ${bytes.length} bytes`);
